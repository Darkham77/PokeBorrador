export type BattleSubStateName = typeof BATTLE_SUBSTATES[keyof typeof BATTLE_SUBSTATES];

export function createBattleStateMachine() {
  const currentState = ref<BattleStateName>(BATTLE_STATES.EXIT_BATTLE);
  const currentSubState = ref<BattleSubStateName | null>(null);
  let transitionCall: gsap.core.Animation | null = null;

  // Simple strict transitions check based on the Mermaid diagram.
  const validTransitions: Record<string, string[]> = {
    [BATTLE_STATES.CONTEXT_SETUP]: [BATTLE_STATES.INITIALIZING],
    [BATTLE_STATES.INITIALIZING]: [BATTLE_STATES.CONTEXT_SETUP, BATTLE_STATES.FIRST_INTRO, BATTLE_STATES.SEARCH_PHASE],
    [BATTLE_STATES.FIRST_INTRO]: [BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.REORDER_TEAM],
    [BATTLE_STATES.SEARCH_PHASE]: [BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.EXIT_BATTLE, BATTLE_STATES.INITIALIZING, BATTLE_STATES.FIRST_INTRO, BATTLE_STATES.REWARDS_PHASE],
    [BATTLE_STATES.ACTIVE_BATTLE]: [BATTLE_STATES.REWARDS_PHASE, BATTLE_STATES.EXIT_BATTLE, BATTLE_STATES.REORDER_TEAM, BATTLE_SUBSTATES.ENEMY_REPLACEMENT_SEQ, BATTLE_SUBSTATES.PLAYER_FAINT_SEQ, BATTLE_STATES.LEVEL_UP_MODAL], 
    [BATTLE_STATES.REWARDS_PHASE]: [BATTLE_STATES.REORDER_TEAM, BATTLE_STATES.SEARCH_PHASE, BATTLE_STATES.INITIALIZING, BATTLE_STATES.EXIT_BATTLE, BATTLE_SUBSTATES.EMPTY_WAIT, BATTLE_SUBSTATES.DISTRIBUTE_XP, BATTLE_STATES.LEVEL_UP_MODAL],
    [BATTLE_STATES.LEVEL_UP_MODAL]: [BATTLE_STATES.REWARDS_PHASE, BATTLE_STATES.SEARCH_PHASE, BATTLE_STATES.INITIALIZING, BATTLE_STATES.ACTIVE_BATTLE],
    [BATTLE_STATES.REORDER_TEAM]: [BATTLE_STATES.SEARCH_PHASE, BATTLE_STATES.INITIALIZING, BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.EXIT_BATTLE],
    [BATTLE_SUBSTATES.ENEMY_DEFEAT]: [BATTLE_STATES.REWARDS_PHASE],
    [BATTLE_SUBSTATES.PLAYER_FAINT_SEQ]: [BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.EXIT_BATTLE],
    [BATTLE_SUBSTATES.ESCAPE_PROCESS]: [BATTLE_STATES.REWARDS_PHASE, BATTLE_STATES.EXIT_BATTLE],
    [BATTLE_STATES.EXIT_BATTLE]: [BATTLE_STATES.CONTEXT_SETUP, BATTLE_STATES.INITIALIZING]
  };

  /**
   * Translates to a specific state or substate.
   * If a delay is provided, returns a Promise that resolves when the transition happens.
   */
  const transition = (newState: BattleStateName | BattleSubStateName, newSubState: BattleSubStateName | null = null, delayMs: number = 0): Promise<void> => {
    return new Promise<void>((resolve) => {
      if (transitionCall) {
        transitionCall.kill();
        transitionCall = null;
      }

      const executeTransition = () => {
        // Validation check (can be expanded for strict enforcement)
        if (newState && (Object.values(BATTLE_STATES) as readonly string[]).includes(newState)) {
          const isSameState = currentState.value === newState;
          const allowedTransitions = validTransitions[currentState.value];
          if (!isSameState && allowedTransitions && !allowedTransitions.includes(newState) && newState !== BATTLE_STATES.EXIT_BATTLE) {
            logger.warn('FSM', `Unexpected transition: ${currentState.value} -> ${newState}`);
          }
          currentState.value = newState as BattleStateName;
        } else if (newState && (Object.values(BATTLE_SUBSTATES) as readonly string[]).includes(newState)) {
          // Si recibimos un sub-estado como primer argumento, mantenemos el estado actual 
          newSubState = newState as BattleSubStateName;
        }

        if (newSubState) {
          currentSubState.value = newSubState;
        } else if (newState && currentState.value !== BATTLE_STATES.ACTIVE_BATTLE) {
          currentSubState.value = null; // Solo limpiamos substate si estamos cambiando de fase principal
        }

        logger.debug('Battle FSM', `Transitioned to ${currentState.value}${currentSubState.value ? ' (' + currentSubState.value + ')' : ''}`);
        resolve(undefined);
      };

      if (delayMs > 0) {
        transitionCall = gsap.delayedCall(delayMs / 1000, executeTransition);
      } else {
        executeTransition();
      }
    });
  };

  const isState = (state: string) => currentState.value === state;
  const isSubState = (subState: string | null) => currentSubState.value === subState;

  return {
    currentState,
    currentSubState,
    transition,
    isState,
    isSubState
  };
}
