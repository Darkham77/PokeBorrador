export function createBattleStateMachine() {
  const currentState = ref(BATTLE_STATES.EXIT_BATTLE);
  const currentSubState = ref(null);
  let transitionTimeout = null;

  // Simple strict transitions check based on the Mermaid diagram.
  const validTransitions = {
    [BATTLE_STATES.CONTEXT_SETUP]: [BATTLE_STATES.INITIALIZING],
    [BATTLE_STATES.INITIALIZING]: [BATTLE_STATES.FIRST_INTRO, BATTLE_STATES.SEARCH_PHASE],
    [BATTLE_STATES.FIRST_INTRO]: [BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.REORDER_TEAM],
    [BATTLE_STATES.SEARCH_PHASE]: [BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.EXIT_BATTLE, BATTLE_STATES.INITIALIZING, BATTLE_STATES.FIRST_INTRO, BATTLE_STATES.REWARDS_PHASE],
    [BATTLE_STATES.ACTIVE_BATTLE]: [BATTLE_STATES.REWARDS_PHASE, BATTLE_STATES.EXIT_BATTLE, BATTLE_STATES.REORDER_TEAM, BATTLE_SUBSTATES.RESOLVE_ENEMY_FAINT, BATTLE_SUBSTATES.RESOLVE_PLAYER_FAINT], 
    [BATTLE_STATES.REWARDS_PHASE]: [BATTLE_STATES.REORDER_TEAM, BATTLE_STATES.SEARCH_PHASE, BATTLE_STATES.INITIALIZING, BATTLE_STATES.EXIT_BATTLE, BATTLE_SUBSTATES.EMPTY_WAIT, BATTLE_SUBSTATES.DISTRIBUTE_XP],
    [BATTLE_STATES.LEVEL_UP_MODAL]: [BATTLE_STATES.REWARDS_PHASE, BATTLE_STATES.SEARCH_PHASE, BATTLE_STATES.INITIALIZING],
    [BATTLE_STATES.REORDER_TEAM]: [BATTLE_STATES.SEARCH_PHASE, BATTLE_STATES.INITIALIZING, BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.EXIT_BATTLE],
    [BATTLE_SUBSTATES.RESOLVE_ENEMY_FAINT]: [BATTLE_SUBSTATES.ENEMY_DEFEAT],
    [BATTLE_SUBSTATES.RESOLVE_PLAYER_FAINT]: [BATTLE_SUBSTATES.PLAYER_FAINT_SEQ],
    [BATTLE_SUBSTATES.ENEMY_DEFEAT]: [BATTLE_STATES.REWARDS_PHASE],
    [BATTLE_SUBSTATES.PLAYER_FAINT_SEQ]: [BATTLE_STATES.ACTIVE_BATTLE, BATTLE_STATES.EXIT_BATTLE],
    [BATTLE_SUBSTATES.ESCAPE_PROCESS]: [BATTLE_STATES.REWARDS_PHASE, BATTLE_STATES.EXIT_BATTLE],
    [BATTLE_STATES.EXIT_BATTLE]: [BATTLE_STATES.CONTEXT_SETUP, BATTLE_STATES.INITIALIZING]
  };

  /**
   * Translates to a specific state or substate.
   * If a delay is provided, returns a Promise that resolves when the transition happens.
   */
  const transition = (newState, newSubState = null, delayMs = 0) => {
    return new Promise((resolve) => {
      if (transitionTimeout) {
        clearTimeout(transitionTimeout);
        transitionTimeout = null;
      }

      const executeTransition = () => {
        // Validation check (can be expanded for strict enforcement)
        if (newState && Object.values(BATTLE_STATES).includes(newState)) {
          const isSameState = currentState.value === newState;
          if (!isSameState && validTransitions[currentState.value] && !validTransitions[currentState.value].includes(newState) && newState !== BATTLE_STATES.EXIT_BATTLE) {
            console.warn(`[FSM] Unexpected transition: ${currentState.value} -> ${newState}`);
          }
          currentState.value = newState;
        } else if (newState && Object.values(BATTLE_SUBSTATES).includes(newState)) {
          // Si recibimos un sub-estado como primer argumento, mantenemos el estado actual 
          // a menos que sea necesario forzar uno (pero GEN_NEW_S2 es background)
          newSubState = newState;
        }

        if (newSubState) {
          currentSubState.value = newSubState;
        } else if (newState && currentState.value !== BATTLE_STATES.ACTIVE_BATTLE) {
          currentSubState.value = null; // Solo limpiamos substate si estamos cambiando de fase principal
        }

        console.log(`[Battle FSM] Transitioned to ${currentState.value}${currentSubState.value ? ' (' + currentSubState.value + ')' : ''}`);
        resolve();
      };

      if (delayMs > 0) {
        transitionTimeout = setTimeout(executeTransition, delayMs);
      } else {
        executeTransition();
      }
    });
  };

  const isState = (state) => currentState.value === state;
  const isSubState = (subState) => currentSubState.value === subState;

  return {
    currentState,
    currentSubState,
    transition,
    isState,
    isSubState
  };
}
